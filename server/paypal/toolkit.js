import { PayPalAgentToolkit } from '@paypal/agent-toolkit/openai'
import { config, modes } from '../config.js'
import { getPaypal } from './index.js'

// Only the read tools the Close Agent may use. Writes never go through the toolkit: approval
// buttons call close/actions.js, which calls PayPal itself.
export const TOOLKIT_ACTIONS = {
  transactions: { list: true },
  orders: { get: true },
  invoices: { get: true, search: true },
}

// The toolkit defaults to the LIVE PayPal API unless context.sandbox is true.
const toolkit = new PayPalAgentToolkit({
  clientId: config.paypalClientId || 'mock-client-id',
  clientSecret: config.paypalClientSecret || 'mock-client-secret',
  configuration: { actions: TOOLKIT_ACTIONS, context: { sandbox: true } },
})

const tools = new Map(toolkit.getTools().map((t) => [t.function.name, t.function]))
export const toolkitToolNames = () => [...tools.keys()]

// JSON Schema generated by the toolkit, reshaped for Claude's input_schema.
export function toolkitSchema(name) {
  const fn = tools.get(name)
  if (!fn) throw new Error(`PayPal toolkit tool ${name} is not enabled`)
  const { $schema, ...schema } = fn.parameters
  return { name, description: fn.description.trim(), input_schema: schema }
}

let counter = 0
async function live(name, args) {
  counter += 1
  const result = await toolkit.handleToolCall({ id: `call_${counter}`, type: 'function', function: { name, arguments: JSON.stringify(args) } })
  const parsed = JSON.parse(result.content)
  if (parsed?.error) throw new Error(`PayPal ${name}: ${typeof parsed.error === 'string' ? parsed.error : parsed.error.message}`)
  return parsed
}

// Same tool names and arguments in both modes. In mock mode the call lands on the mock world.
export async function callToolkit(name, args) {
  if (!tools.has(name)) throw new Error(`PayPal toolkit tool ${name} is not enabled`)
  if (modes.paypal === 'sandbox') return live(name, args)
  const paypal = getPaypal()
  if (name === 'list_transactions') return paypal.searchTransactions({ startDate: args.start_date, endDate: args.end_date, transactionStatus: args.transaction_status || 'S', transactionId: args.transaction_id, page: args.page, pageSize: args.page_size || 100, fields: 'all' })
  if (name === 'get_order') return paypal.getOrder(args.id)
  if (name === 'get_invoice') return paypal.getInvoice(args.invoice_id)
  if (name === 'search_invoicing') return paypal.searchInvoices({ invoiceNumber: args.invoice_filters?.invoice_number })
  throw new Error(`No mock for ${name}`)
}

